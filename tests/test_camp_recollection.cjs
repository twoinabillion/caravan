const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const env=vm.createContext({console,setTimeout:()=>0,clearTimeout:()=>{}});
const source=name=>fs.readFileSync('src/'+name,'utf8');
vm.runInContext(source('03-data.js')+'\nglobalThis.data=D;',env);
vm.runInContext(source('03j-camp-conversations.js'),env);
env.S={party:['minji'],day:4,min:1210,campNight:0,comps:{},campMemories:{}};
env.G={recruitApproach:()=>null};
vm.runInContext(source('04e-engine-world.js'),env);
