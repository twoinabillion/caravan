const results={};
for(const code of ['success','partial','failure','retreat']){
 env.S.lastCombatReport={...report,resultCode:code};
 const before=JSON.stringify(env.S),text=env.G.campContext('minji');results[code]=text;
 assert(text.includes('비탈'),'recollection remembers the actual incident');
 assert(!/13\.9|연료 -2|기록에 남은 고비|대가로|목표|고정 ·/.test(text),'recollection is not a mechanics receipt');
 assert(text.length<120&&!text.includes('\n\n'),'one short recollection before the authored conversation');
 assert.equal(JSON.stringify(env.S),before,'reading does not change history');
}
assert.equal(new Set(Object.values(results)).size,4,'success, partial, failure and retreat stay distinct');
assert(results.success.includes('해냈다'));assert(results.partial.includes('끝내지는 못했다'));
assert(results.failure.includes('해내지 못했다'));assert(results.retreat.includes('물러났다'));
env.S.lastCombatReport={...report,resultCode:'unknown'};
assert(!/해냈|죽|다쳤|구했/.test(env.G.campContext('minji')),'unknown outcome never becomes a success or injury');
env.S.lastCombatReport={...report,resultCode:'success',day:1};
env.G.recruitApproach=()=>({label:'고철 3개를 지불한다',memory:'민지와 흩어진 공구를 주웠다.'});
assert.equal(env.G.campContext('minji'),'민지와 흩어진 공구를 주웠다.','old combat and UI choice labels do not intrude');
env.S.campMemories.minji={visits:1};env.S.lastJourneyRecap={from:'yangsan',to:'miryang',day:4};
assert(env.G.campContext('minji').includes('밀양'),'returning visits move on from the recruitment recap');
env.S.lastJourneyRecap=null;assert.equal(env.G.campContext('minji'),'','no fabricated anecdote when nothing is recent');
