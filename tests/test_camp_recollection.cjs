env.S.campConversation={id:'camp_0_minji',night:0,cid:'minji',timeLabel:'밤',context:legacy,revisit:false,chapter:1,choiceId:null,chips:[],active:true};
env.S.lastCombatReport={...report,resultCode:'success',day:4};
const frozen=JSON.stringify(env.S.campConversation),event=env.G.campConversationEvent();
assert(!event.turns[0].text.includes('13.9')&&!event.turns[0].text.includes('목표'),'legacy text gets a clean presentation');
assert(event.turns[0].text.includes('해내지 못했다'),'legacy failure never borrows the newer success');
assert.equal(event.readingRecord,legacy,'old saved context stays available as its original record');
assert.equal(JSON.stringify(env.S.campConversation),frozen,'legacy rendering cannot rewrite the saved conversation');
env.S.campConversation.context='그날 실패와 민지의 이야기를 이미 남겼다.';
